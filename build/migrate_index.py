#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Rebuild foundations and patterns from the original index.html.

The first foundations migration drew on `guidelines/*.card.html`, which turned
out to be a much thinner source: the original index page carried ten foundation
sections and eight pattern sections that exist nowhere else, including the
primitive palette tables and the full colour accessibility audit.

This script reads those sections straight out of the old index page and splits
them into one page per entry.

    python3 build/migrate_index.py ../previous-version

Authored content under _content/ is never overwritten.
"""

import json
import re
import sys
from pathlib import Path
from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parent.parent
OLD = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT
CONTENT = ROOT / "_content"

# entry slug -> section id in the old index.html
FOUNDATIONS = {
    "architecture": ["architecture"],
    "palette": ["palette"],
    "semantic-colour": ["color"],
    "typography": ["type"],
    "spacing": ["space"],
    "shape": ["shape"],
    "elevation": ["elevation"],
    "motion": ["motion"],
    "colour-accessibility": ["a11y"],
    "interaction-states": ["states"],
}

PATTERNS = {
    "page-header": ["p-pageheader"],
    "product-grid": ["p-product"],
    "filter-bar": ["p-filter"],
    "form-layout": ["p-form"],
    "order-summary": ["p-summary"],
    "data-table": ["p-table"],
    "empty-state": ["p-empty"],
    "status-messaging": ["p-messaging"],
}

# the three sample-data strings that were never translated
FIXUPS = {
    "Deniz Aydın": "Deniz Aydin",
    "Bağdat Cad. 128/4": "128/4 Bagdat Cad.",
    "İstanbul": "Istanbul",
}


def load_index():
    p = OLD / "index.html"
    if not p.exists():
        sys.exit(f"no index.html at {p}")
    return BeautifulSoup(p.read_text(encoding="utf-8"), "html.parser")


def extract(soup, ids):
    """Pull sections out, keeping their markup but dropping stale ids and anchors."""
    parts = []
    for sid in ids:
        sec = soup.find("section", id=sid)
        if not sec:
            print(f"    ! section #{sid} not found")
            continue

        # ids are regenerated by the build from each <h2>
        del sec["id"]

        # the old page was one long document, so its links are same-page
        # fragments that mean nothing once the content is split up
        for a in sec.find_all("a", href=True):
            if a["href"].startswith("#"):
                a.unwrap()

        # the section eyebrow duplicates the new page header
        for cap in sec.find_all(class_="cap"):
            if cap.get_text(strip=True).lower() in ("foundations", "patterns", "components"):
                cap.decompose()

        for lead in sec.find_all("p", class_="lead"):
            lead["class"] = ["doc-lead"]

        html = str(sec)
        for tr, en in FIXUPS.items():
            html = html.replace(tr, en)
        parts.append(html)
    return "\n".join(parts)


def write(section_id, slug, html):
    target = CONTENT / section_id / slug / "index.html"
    if target.exists():
        return "authored"
    if not html.strip():
        return "empty"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html, encoding="utf-8")
    return "migrated"


def main():
    soup = load_index()
    for label, section_id, mapping in (
        ("Foundations", "foundations", FOUNDATIONS),
        ("Patterns", "patterns", PATTERNS),
    ):
        print(f"\n{label}")
        for slug, ids in mapping.items():
            html = extract(soup, ids)
            r = write(section_id, slug, html)
            size = len(html)
            print(f"  {slug:24} {r:10} {size:6} bytes")


if __name__ == "__main__":
    main()
